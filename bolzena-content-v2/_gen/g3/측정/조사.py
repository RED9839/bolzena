def limits(src):
    o = {}
    for f in ('무기.json', '방어구.json', '장신구.json', '교주카드.json'):
        d = json.load(open(os.path.join(src, f), encoding='utf-8'))
        for it in d.get('equips') or d.get('cards'):
            s = json.dumps(it, ensure_ascii=False)
            lim = re.findall(r'"limit": \{"per": "(\w+)", "n": (\d+)\}', s)
            rnd = s.count('"ifRandom"')
            o[it['name']] = ('턴당 ' + '·'.join(sorted({n for p, n in lim})) + '회' if lim else '') + (f' 확률 {rnd}' if rnd else '')
    return o

def main():
    a = kit(sys.argv[1]); pa, ba = probe(sys.argv[2]); lim = limits(sys.argv[3])
    print(f'바탕 완주(아무것도 안 줌, 같은 900판): {ba}%\n')
    for kind, title in (('장비', '장비 64'), ('교주', '교주 카드 43')):
        print(f'### {title}\n')
        print('| 이름 | 등급 | 효과(전) | 봇 값 | 제한 · 확률 | 쥐여 주기 %p | 문제 |')
        print('|---|---|---|---|---|---|---|')
        for n, x in a.items():
            if x['kind'] != kind: continue
            eff = x['lines'][0].replace('기본  ', '')
            if kind == '장비':
                eff = re.sub(r'^(HP|공격력|방어력|치명) [^·]*(· (HP|공격력|방어력|치명) [^·]*)*(· )?', '', eff) or '(능력치만)'
            p = pa.get(n)
            print(f"| {n} | {x['grade']} | {eff.replace('|', '/')} | {x['val']} | {lim.get(n, '')} | {p['d']:+.1f} | {NOTE.get(n, '')} |" if p else
                  f"| {n} | {x['grade']} | {eff.replace('|', '/')} | {x['val']} | {lim.get(n, '')} | - | {NOTE.get(n, '')} |")
        print()

if __name__ == '__main__':
    main()
