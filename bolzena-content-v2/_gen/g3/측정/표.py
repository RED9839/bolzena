def kit(path):
    o = {}; cur = None
    for l in open(path, encoding='utf-8'):
        l = l.rstrip('\n')
        m = re.match(r'\[(장비|교주)\] (.+?) \((\S+) · (.+?)\) 값 ([\d.]+)', l)
        if m:
            cur = {'kind': m.group(1), 'name': m.group(2), 'grade': m.group(3), 'meta': m.group(4), 'val': float(m.group(5)), 'lines': []}
            o[cur['name']] = cur; continue
        if cur and l.startswith('  ') and not l.startswith('  「'): cur['lines'].append(l.strip())
    return o

def probe(path):
    o = {}; base = None
    if not path or not os.path.exists(path): return o, None
    for l in open(path, encoding='utf-8'):
        p = l.rstrip('\n').split('\t')
        if len(p) < 7: continue
        if p[0] == '바탕': base = float(p[5]); continue
        o[p[2]] = {'rate': float(p[5]), 'd': float(p[6]), 'kept': p[7] if len(p) > 7 else '-'}
    return o, base

