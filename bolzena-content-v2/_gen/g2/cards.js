const TYPES = ['공격', '스킬', '강화'];

function build() {
  const { spells } = L.readRef();
  const out = [], rows = [];
  const PRICE_BASE = { 일반: 50, 고급: 80, 희귀: 110, 전설: 150 };
  for (const [id, name, cost, type, tags, fx, oracles, blesses, blurb] of DEF) {
    const s = spells.find(x => x.name === name);
    if (!s) throw new Error('원작 표에 없는 스펠: ' + name);
    if (!TYPES.includes(type)) throw new Error(`카드 종류는 공격 · 스킬 · 강화 — ${id}: ${type}`);
    const price = Math.min(240, Math.round((PRICE_BASE[s.grade] + s.coin * 2.5) / 10) * 10);
    const c = { id, name, cost, type };
    if (tags.length) c.tags = tags;
    Object.assign(c, { grade: s.grade, price, fx, oracles, blesses, blurb });
    out.push(c);
    rows.push({ id, name, grade: s.grade, coin: s.coin, cost, type, price, icon: s.icon });
  }
  for (const s of spells) if (!DEF.some(d => d[1] === s.name)) throw new Error('빠진 스펠: ' + s.name);
  if (out.length !== 43) throw new Error('교주 카드 수 ' + out.length);
  return { cards: out, rows };
}
module.exports = { build };
