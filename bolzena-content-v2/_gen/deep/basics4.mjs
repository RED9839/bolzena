const ROLE_DEF = { 탱커: 'shield', 서포터: 'heal', 딜러: 'shield' };
/** 기본 카드를 4장으로 · 시작 덱 = 기본 4 + 시동(고유 중 시작 덱에 있던 것). 3성 · 마리만. */
export function addBasics(j) {
  const h = j.heroes[0]; if (h.star < 3 && h.id !== '마리') return;
  const n = NAMES[h.id]; if (!n) throw new Error('기본 카드 이름 없음 ' + h.id);
  const basics = () => j.cards.filter(c => c.hero === h.id && !c.token && !c.unique);
  const kws = [h.keyword, ...(h.keywords || [])].filter(Boolean); const k = kws[0];
  let i = basics().length;
  const add = c => { if (basics().length >= 4) return; i++; j.cards.push({ id: `${h.id}_s${i}`, name: c.name, hero: h.id, cost: c.cost, type: c.type, fx: c.fx }); };
  if (n.h) add({ name: n.h, cost: 2, type: '공격', fx: [{ k: 'dmg', ratio: h.role === '딜러' ? 2.2 : 1.9, target: 'oneEnemy' }] });
  if (n.d) add({ name: n.d, cost: 1, type: '스킬', fx: [{ k: 'shield', ratio: 1.5 }] });
  const st = k.carrier === 'enemy' ? { k: 'stack', id: k.name, v: 2, target: 'oneEnemy' } : (k.carrier === 'hero' ? { k: 'stack', id: k.name, v: 1, target: 'oneAlly' } : { k: 'stack', id: k.name, v: 1 });
  const base = k.carrier === 'enemy' ? { k: 'shield', ratio: 0.6 } : ROLE_DEF[h.role] === 'heal' ? { k: 'heal', ratio: 0.9 } : { k: 'shield', ratio: h.role === '탱커' ? 1.0 : 0.8 };
  add({ name: n.k, cost: 1, type: '스킬', fx: [base, st] });
  // 2026-10-11 사용자: 카제나식 — 기본 3장(1코 공격 · 2코 강타 · 막기, 서포터는 회복 · 딜러는 약화 스킬)을 모두 시작 덱에, 시작 덱 = 기본 3 + 시동 = 4장.
  // 「고유 효과 스킬」(옛 기본 4번째)은 고유 카드로 옮긴다(은총으로 얻음 · 신탁 다섯) — 고유 5장 = 시동 + 고유 3 + 완성형(카제나와 같은 꼴).
  const kc = basics().find(c => c.name === n.k) || basics().find(c => c.type === '스킬' && c.fx.some(q => q.k === 'stack'));
  if (kc) { kc.unique = true; kc.oracles = kOracles(kc); }
  const opener = (h.starter || []).filter(id => j.cards.find(c => c.id === id && c.unique && c !== kc));
  h.starter = [...basics().map(c => c.id), ...opener];
}
/** 옛 기본 「고유 효과 스킬」 의 신탁 다섯 — 수치 · 비용 −1 · 드로우 · 쌓기 · 보존 갈래(값어치는 뒤의 valfix 가 맞춘다). */
function kOracles(c) {
  const cp = x => JSON.parse(JSON.stringify(x));
  const up = (fx, m, dv) => cp(fx).map(q => { if (typeof q.ratio === 'number') q.ratio = Math.round(q.ratio * m * 100) / 100; if (q.k === 'stack' && dv) q.v = (q.v || 1) + dv; return q; });
  return [
    { name: '신탁 1', fx: up(c.fx, 1.5, 1) },
    { name: '신탁 2', cost: Math.max(0, c.cost - 1), fx: cp(c.fx) },
    { name: '신탁 3', fx: c.fx.length < 3 ? [...cp(c.fx), { k: 'draw', v: 1 }] : up(c.fx, 1.2, 1) },
    { name: '신탁 4', fx: up(c.fx, 1, 2) },
    { name: '신탁 5', tags: ['보존'], fx: up(c.fx, 1.3, 0) },
  ];
}
